# Aqueous G_CDS oracle covering the elements whose CDS radius differs from
# their intrinsic Coulomb radius (C, F, Si, S, Cl, Br). The original water
# gate used only H, O, N and P, whose two radius sets coincide, so it could
# not see an area built from the wrong set. Every molecule here is made of
# aqueous pair-term-free element pairs.
from pyscf import gto
from pyscf.solvent import smd

CASES = [
    ("F2", "F 0 0 0; F 0 0 1.412"),
    ("Cl2", "Cl 0 0 0; Cl 0 0 1.988"),
    ("Br2", "Br 0 0 0; Br 0 0 2.281"),
    ("S2", "S 0 0 0; S 0 0 1.889"),
    ("ClF", "Cl 0 0 0; F 0 0 1.628"),
    ("BrCl", "Br 0 0 0; Cl 0 0 2.136"),
    ("SF2", "S 0 0 0; F 0 0 1.587; F 1.520 0 -0.457"),
    ("SiF4", "Si 0 0 0; F 0.904 0.904 0.904; F -0.904 -0.904 0.904; "
             "F 0.904 -0.904 -0.904; F -0.904 0.904 -0.904"),
    ("CF4", "C 0 0 0; F 0.767 0.767 0.767; F -0.767 -0.767 0.767; "
            "F 0.767 -0.767 -0.767; F -0.767 0.767 -0.767"),
    ("CCl4", "C 0 0 0; Cl 1.021 1.021 1.021; Cl -1.021 -1.021 1.021; "
             "Cl 1.021 -1.021 -1.021; Cl -1.021 1.021 -1.021"),
]

print("# PROVENANCE: generated by tools/oracle/gen_smd_water_wide.py against")
print("# PySCF's SMD module, used as a NUMERICAL ORACLE only. Units: Hartree.")
print("# label,g_cds_hartree")
for label, spec in CASES:
    mol = gto.M(atom=spec, basis="sto-3g", spin=None, verbose=0)
    obj = smd.SMD(mol)
    obj.solvent = "water"
    g, _ = smd.get_cds_legacy(obj)
    print(f"{label},{g:.12e}")
