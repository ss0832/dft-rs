# Aqueous G_CDS oracle for the elements BEYOND the nine that carry an
# atomic surface tension. They still need a CDS radius, because the shared
# molecular term multiplies their exposed area — so a wrong radius shows up
# here even though the tension is zero.
#
# Every molecule is built from element pairs measured to be pair-term-free
# in water (measure_smd_water_pairs.py over the expanded element set).
from pyscf import gto
from pyscf.solvent import smd

CASES = [
    ("LiF", "Li 0 0 0; F 0 0 1.564"),
    ("NaCl", "Na 0 0 0; Cl 0 0 2.361"),
    ("KI", "K 0 0 0; I 0 0 3.048"),
    ("BF3", "B 0 0 0; F 1.307 0 0; F -0.653 1.132 0; F -0.653 -1.132 0"),
    ("BeH2", "Be 0 0 0; H 0 0 1.334; H 0 0 -1.334"),
    ("AlH3", "Al 0 0 0; H 1.584 0 0; H -0.792 1.372 0; H -0.792 -1.372 0"),
    ("GeH4", "Ge 0 0 0; H 0.883 0.883 0.883; H -0.883 -0.883 0.883; "
             "H 0.883 -0.883 -0.883; H -0.883 0.883 -0.883"),
    ("AsH3", "As 0 0 0; H 1.399 0 0.616; H -0.700 1.212 0.616; "
             "H -0.700 -1.212 0.616"),
    ("SeH2", "Se 0 0 0; H 0 0 1.460; H 1.420 0 -0.337"),
    ("HI", "H 0 0 0; I 0 0 1.609"),
    ("ICl", "I 0 0 0; Cl 0 0 2.321"),
    ("SnH4", "Sn 0 0 0; H 0.983 0.983 0.983; H -0.983 -0.983 0.983; "
             "H 0.983 -0.983 -0.983; H -0.983 0.983 -0.983"),
    ("SbF3", "Sb 0 0 0; F 1.240 0 1.240; F -1.240 0 1.240; F 0 1.240 -1.240"),
    ("TeH2", "Te 0 0 0; H 0 0 1.658; H 1.610 0 -0.400"),
    ("ZnCl2", "Zn 0 0 0; Cl 0 0 2.072; Cl 0 0 -2.072"),
    ("CaF2", "Ca 0 0 0; F 0 0 2.100; F 0 0 -2.100"),
]

print("# PROVENANCE: generated by tools/oracle/gen_smd_water_elements.py")
print("# against PySCF's SMD module, used as a NUMERICAL ORACLE only.")
print("# Units: Hartree.")
print("# label,g_cds_hartree")
for label, spec in CASES:
    mol = gto.M(atom=spec, basis="sto-3g", spin=None, verbose=0)
    obj = smd.SMD(mol)
    obj.solvent = "water"
    g, _ = smd.get_cds_legacy(obj)
    print(f"{label},{g:.12e}")
