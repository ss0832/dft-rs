//! SOSCF: second-order (Newton) orbital optimization for the SCF endgame.
//!
//! DIIS-family accelerators extrapolate; they do not use curvature. Near a
//! solution the energy is a smooth function of the orbital rotations
//! `kappa` (antisymmetric, occupied-virtual block only), so a Newton step
//!
//! ```text
//!   H kappa = -g,        C <- C exp(kappa)
//! ```
//!
//! converges quadratically where DIIS converges linearly — and, more
//! importantly for hard cases, it cannot oscillate between two solutions
//! the way a residual extrapolation can.
//!
//! `g_ai = 4 F_ai` in the MO basis (closed shell; `2 F_ai` per spin
//! channel when unrestricted) and `H` is the ORBITAL HESSIAN, whose action
//! contains the CPKS density kernel and the current Fock commutator
//!
//! ```text
//!   (H kappa)_ai = (F_vv kappa - kappa F_oo)_ai + G[dP(kappa)]_ai
//! ```
//!
//! with the appropriate restricted/unrestricted gradient normalization.
//! The SCF currently enables this optimizer for complete quadratic
//! Coulomb/exchange models. Other density terms retain SCF/DIIS until their
//! complete optimization kernel is connected to the shared TRAH adapter.
//! That adapter also reuses this orbital frame. The Newton product uses the loop's OWN
//! `JkEngine` rather than through `ResponseSolver`, because the latter
//! constructs a fresh engine — which, in in-core mode, would recompute the
//! whole ERI tensor on every Newton step.
//!
//! The step is taken with a trust radius and only accepted if the energy
//! actually goes down, so a bad Hessian can slow convergence but cannot
//! break it.

use crate::error::Result;
use crate::linalg::Matrix;

/// Orbital-rotation state for one Newton step.
pub struct OrbitalHessian<'a> {
    /// MO coefficients per spin (AO x MO).
    pub c: &'a [Matrix; 2],
    /// MO energies per spin.
    pub eps: &'a [Vec<f64>; 2],
    /// Occupied counts per spin.
    pub n_occ: [usize; 2],
    /// 1 for a restricted calculation, 2 for unrestricted.
    pub spins: usize,
}

impl OrbitalHessian<'_> {
    fn nvir(&self, spin: usize) -> usize {
        self.c[spin].cols - self.n_occ[spin]
    }

    /// Length of the packed rotation vector.
    pub fn len(&self) -> usize {
        (0..self.spins).map(|s| self.n_occ[s] * self.nvir(s)).sum()
    }

    pub fn is_empty(&self) -> bool {
        self.len() == 0
    }

    /// Orbital gradient `g_ai` from the AO-basis Fock matrices.
    ///
    /// At convergence this is zero, which is the same statement as
    /// `FPS - SPF = 0` — so its norm is directly comparable to the DIIS
    /// error and can drive the handover.
    pub fn gradient(&self, fock: &[Matrix]) -> Vec<f64> {
        let mut g = vec![0.0; self.len()];
        let scale = if self.spins == 1 { 4.0 } else { 2.0 };
        let mut off = 0;
        for spin in 0..self.spins {
            let (no, nv) = (self.n_occ[spin], self.nvir(spin));
            let c = &self.c[spin];
            let f = &fock[spin.min(fock.len() - 1)];
            let fc = f.matmul_accurate(c, false);
            for a in 0..nv {
                for i in 0..no {
                    let mut acc = crate::linalg::AccurateSum::default();
                    for mu in 0..c.rows {
                        acc.add_product(c[(mu, no + a)], fc[(mu, i)]);
                    }
                    g[off + a * no + i] = scale * acc.value();
                }
            }
            off += no * nv;
        }
        g
    }

    /// The density change generated by a rotation, per spin, in the AO
    /// basis: `dP = C_o kappa^T C_v^T + C_v kappa C_o^T`, times the
    /// occupation factor.
    pub fn delta_density(&self, kappa: &[f64]) -> [Matrix; 2] {
        let nao = self.c[0].rows;
        let mut out = [Matrix::zeros(nao, nao), Matrix::zeros(nao, nao)];
        // PER SPIN, with no occupation factor: the caller sums the two
        // channels to get the total density, which supplies the factor of
        // two for a restricted case automatically. Putting the 2 in here
        // instead makes the EXCHANGE term twice too large, because K is
        // built from the spin density while J is built from the total --
        // measured as SOSCF making HF converge in 16 iterations instead
        // of 11.
        let occ = 1.0;
        let mut off = 0;
        for spin in 0..self.spins {
            let (no, nv) = (self.n_occ[spin], self.nvir(spin));
            let c = &self.c[spin];
            for a in 0..nv {
                for i in 0..no {
                    let k = kappa[off + a * no + i];
                    if k == 0.0 {
                        continue;
                    }
                    for mu in 0..nao {
                        let cva = c[(mu, no + a)];
                        let cmi = c[(mu, i)];
                        if cva == 0.0 && cmi == 0.0 {
                            continue;
                        }
                        for nu in 0..nao {
                            out[spin][(mu, nu)] +=
                                occ * k * (cva * c[(nu, i)] + cmi * c[(nu, no + a)]);
                        }
                    }
                }
            }
            off += no * nv;
        }
        if self.spins == 1 {
            out[1] = out[0].clone();
        }
        out
    }

    /// Finite density change along the unitary orbital path, evaluated as
    /// sum ad_K^n(D0)/n!. Unlike subtracting two occupied projectors, this
    /// retains the quadratic diagonal population change at arbitrarily small
    /// rotations. Used for exact quadratic energy work, not for a finite
    /// difference or a modified convergence threshold.
    pub fn finite_density_change(&self, kappa: &[f64]) -> [Matrix; 2] {
        let nao = self.c[0].rows;
        let mut out = [Matrix::zeros(nao, nao), Matrix::zeros(nao, nao)];
        let mut offset = 0;
        for spin in 0..self.spins {
            let no = self.n_occ[spin];
            let n = self.c[spin].cols;
            let delta = orbital_density_change(n, no, &kappa[offset..offset + no * (n - no)]);
            out[spin] = self.c[spin]
                .matmul_seq(&delta)
                .matmul_transpose_seq(&self.c[spin]);
            offset += no * (n - no);
        }
        if self.spins == 1 {
            out[1] = out[0].clone();
        }
        out
    }

    /// Exact quadratic-functional energy work along the finite unitary path.
    /// The linear work is contracted in the orbital frame: AO-space first-order
    /// cancellations against large core energies never hide the O(kappa^2)
    /// population terms. The induced-Fock work is already quadratic.
    pub(crate) fn quadratic_energy_work(
        &self,
        kappa: &[f64],
        fock: &[Matrix; 2],
        delta: &[Matrix; 2],
        induced: &[Matrix; 2],
    ) -> f64 {
        let mut sum = crate::linalg::AccurateSum::default();
        let mut offset = 0;
        for spin in 0..self.spins {
            let n = self.c[spin].cols;
            let no = self.n_occ[spin];
            let change = orbital_density_change(n, no, &kappa[offset..offset + no * (n - no)]);
            let f = self.c[spin]
                .matmul_accurate(&fock[spin].matmul_accurate(&self.c[spin], false), true);
            for (&p, &v) in change.as_slice().iter().zip(f.as_slice()) {
                sum.add_product(p, v);
            }
            for (&p, &v) in delta[spin].as_slice().iter().zip(induced[spin].as_slice()) {
                sum.add_product(0.5 * p, v);
            }
            offset += no * (n - no);
        }
        sum.value() * if self.spins == 1 { 2.0 } else { 1.0 }
    }

    /// Project an AO-basis operator onto the occupied-virtual block.
    pub fn project(&self, ao: &[Matrix; 2]) -> Vec<f64> {
        let mut out = vec![0.0; self.len()];
        let scale = if self.spins == 1 { 4.0 } else { 2.0 };
        let mut off = 0;
        for spin in 0..self.spins {
            let (no, nv) = (self.n_occ[spin], self.nvir(spin));
            let c = &self.c[spin];
            let gc = ao[spin].matmul(c);
            for a in 0..nv {
                for i in 0..no {
                    let mut acc = 0.0;
                    for mu in 0..c.rows {
                        acc += c[(mu, no + a)] * gc[(mu, i)];
                    }
                    out[off + a * no + i] = scale * acc;
                }
            }
            off += no * nv;
        }
        out
    }

    /// Orbital-energy denominators, used as the PCG preconditioner and as
    /// the fallback step when the Hessian product is unavailable.
    pub fn diagonal(&self) -> Vec<f64> {
        let mut d = vec![0.0; self.len()];
        let scale = if self.spins == 1 { 4.0 } else { 2.0 };
        let mut off = 0;
        for spin in 0..self.spins {
            let (no, nv) = (self.n_occ[spin], self.nvir(spin));
            let e = &self.eps[spin];
            for a in 0..nv {
                for i in 0..no {
                    d[off + a * no + i] = scale * (e[no + a] - e[i]).max(1e-6);
                }
            }
            off += no * nv;
        }
        d
    }

    /// Exact fixed-potential orbital Hessian at the current orbitals.
    /// Full occupied/virtual Fock blocks are retained: stored canonical
    /// energies are only a preconditioner after an orbital rotation.
    pub fn fock_commutator(&self, kappa: &[f64], fock: &[Matrix; 2]) -> Vec<f64> {
        let mut out = vec![0.0; self.len()];
        let mut off = 0;
        let scale = if self.spins == 1 { 4.0 } else { 2.0 };
        for spin in 0..self.spins {
            let no = self.n_occ[spin];
            let nv = self.nvir(spin);
            let f = self.c[spin]
                .transpose_matmul_seq(&fock[spin])
                .matmul_seq(&self.c[spin]);
            for a in 0..nv {
                for i in 0..no {
                    let mut value = 0.0;
                    for b in 0..nv {
                        value += f[(no + a, no + b)] * kappa[off + b * no + i];
                    }
                    for j in 0..no {
                        value -= kappa[off + a * no + j] * f[(j, i)];
                    }
                    out[off + a * no + i] = scale * value;
                }
            }
            off += no * nv;
        }
        out
    }
}

pub(crate) fn generator(nmo: usize, occupied: usize, packed: &[f64]) -> Matrix {
    let mut k = Matrix::zeros(nmo, nmo);
    for a in occupied..nmo {
        for i in 0..occupied {
            let value = packed[(a - occupied) * occupied + i];
            k[(a, i)] = value;
            k[(i, a)] = -value;
        }
    }
    k
}

fn orbital_density_change(n: usize, no: usize, packed: &[f64]) -> Matrix {
    let k = generator(n, no, packed);
    generator_density_change(&k, no)
}

fn generator_density_change(k: &Matrix, no: usize) -> Matrix {
    let n = k.rows;
    let mut term = Matrix::zeros(n, n);
    for i in 0..n {
        for j in 0..n {
            term[(i, j)] =
                k[(i, j)] * ((if j < no { 1.0 } else { 0.0 }) - (if i < no { 1.0 } else { 0.0 }));
        }
    }
    let mut delta = term.clone();
    for order in 2..=64 {
        let left = k.matmul_seq(&term);
        let right = term.matmul_seq(k);
        for i in 0..n * n {
            term.as_mut_slice()[i] = (left.as_slice()[i] - right.as_slice()[i]) / order as f64;
            delta.as_mut_slice()[i] += term.as_slice()[i];
        }
        let size = delta.as_slice().iter().fold(0.0_f64, |m, x| m.max(x.abs()));
        let remainder = term.as_slice().iter().fold(0.0_f64, |m, x| m.max(x.abs()));
        if remainder <= f64::EPSILON * size {
            break;
        }
    }
    delta
}

/// Solve `H kappa = -g` by preconditioned conjugate gradients.
///
/// `hx` supplies the Hessian-vector product; the caller owns the Fock
/// build, so the SCF's existing engine is reused instead of a new one.
/// Failure to converge is not an error: a partially converged Newton
/// direction is still a descent direction, and the caller line-searches.
pub fn newton_direction<F>(
    oh: &OrbitalHessian<'_>,
    g: &[f64],
    mut hx: F,
    max_iter: usize,
    tol: f64,
) -> Result<Vec<f64>>
where
    F: FnMut(&[f64]) -> Result<Vec<f64>>,
{
    newton_direction_diagonal(&oh.diagonal(), g, &mut hx, max_iter, tol)
}

/// The same truncated Newton iteration for other constrained orbital spaces.
pub(crate) fn newton_direction_diagonal(
    diag: &[f64],
    g: &[f64],
    mut hx: impl FnMut(&[f64]) -> Result<Vec<f64>>,
    max_iter: usize,
    tol: f64,
) -> Result<Vec<f64>> {
    let n = g.len();
    let mut x = vec![0.0; n];
    let mut r: Vec<f64> = g.iter().map(|v| -v).collect();
    let mut z: Vec<f64> = r.iter().zip(diag).map(|(a, d)| a / d).collect();
    let mut p = z.clone();
    let mut rz: f64 = r.iter().zip(&z).map(|(a, b)| a * b).sum();
    let g_norm: f64 = g.iter().map(|v| v * v).sum::<f64>().sqrt();
    if g_norm == 0.0 {
        return Ok(x);
    }
    for _ in 0..max_iter {
        let ap = hx(&p)?;
        let pap: f64 = p.iter().zip(&ap).map(|(a, b)| a * b).sum();
        if pap <= 0.0 || !pap.is_finite() {
            // Negative curvature: the quadratic model is not trustworthy
            // in this direction. Stop and hand back what we have, which is
            // still downhill.
            break;
        }
        let alpha = rz / pap;
        for i in 0..n {
            x[i] += alpha * p[i];
            r[i] -= alpha * ap[i];
        }
        let rnorm: f64 = r.iter().map(|v| v * v).sum::<f64>().sqrt();
        if rnorm < tol * g_norm {
            break;
        }
        for i in 0..n {
            z[i] = r[i] / diag[i];
        }
        let rz_new: f64 = r.iter().zip(&z).map(|(a, b)| a * b).sum();
        let beta = rz_new / rz;
        rz = rz_new;
        for i in 0..n {
            p[i] = z[i] + beta * p[i];
        }
    }
    Ok(x)
}

/// Rotate the MO coefficients by `exp(kappa)`, truncated where the series
/// is already converged to machine precision.
///
/// The rotation is applied in the MO basis, so orthonormality is preserved
/// by construction rather than restored afterwards — no re-orthogonalization
/// step, and no slow drift over many iterations.
pub fn rotate(oh: &OrbitalHessian<'_>, kappa: &[f64], out: &mut [Matrix; 2]) {
    let mut off = 0;
    for spin in 0..oh.spins {
        let (no, nv) = (oh.n_occ[spin], oh.nvir(spin));
        let nmo = no + nv;
        let k = generator(nmo, no, &kappa[off..off + no * nv]);
        // exp(K) by scaling and squaring. A plain Taylor series is fine for
        // the small rotations SOSCF actually takes, but it loses
        // orthonormality once |K| approaches one — and orthonormality is
        // the entire reason for rotating instead of re-diagonalizing, so
        // it must hold for ANY step the trust region might produce.
        out[spin] = oh.c[spin].matmul(&orthogonal_exponential(&k));
        off += no * nv;
    }
    if oh.spins == 1 {
        out[1] = out[0].clone();
    }
}

/// Shared retraction for a real antisymmetric generator.
pub(crate) fn orthogonal_exponential(k: &Matrix) -> Matrix {
    let nmo = k.rows;
    let norm = k.as_slice().iter().fold(0.0f64, |acc, v| acc.max(v.abs()));
    let squarings = if norm > 0.5 {
        ((norm / 0.5).log2().ceil() as i32).max(0) as usize
    } else {
        0
    };
    let scale = 1.0 / (1u64 << squarings) as f64;
    let mut ks = k.clone();
    for t in ks.as_mut_slice() {
        *t *= scale;
    }
    let mut u = Matrix::identity(nmo);
    let mut term = Matrix::identity(nmo);
    for order in 1..=20 {
        term = term.matmul(&ks);
        for t in term.as_mut_slice() {
            *t /= order as f64;
        }
        let mut small = true;
        for (uv, tv) in u.as_mut_slice().iter_mut().zip(term.as_slice()) {
            *uv += *tv;
            if tv.abs() > 1e-18 {
                small = false;
            }
        }
        if small {
            break;
        }
    }
    for _ in 0..squarings {
        u = u.matmul(&u);
    }
    u
}

/// Energy Hessian on one common spatial-orbital frame with two occupations.
/// Unlike independent-spin rotations, this retains the closed/open/virtual
/// constraint and the connection terms away from a stationary determinant.
pub(crate) struct CommonOrbitalHessian<'a> {
    c: &'a Matrix,
    fock: [Matrix; 2],
    counts: [usize; 2],
    pairs: Vec<(usize, usize)>,
}

impl<'a> CommonOrbitalHessian<'a> {
    pub(crate) fn new(c: &'a Matrix, fock: &[Matrix; 2], counts: [usize; 2]) -> Self {
        let pairs = (0..c.cols)
            .flat_map(|p| (p + 1..c.cols).map(move |q| (p, q)))
            .filter(|&(p, q)| counts.iter().any(|&n| (p < n) != (q < n)))
            .collect();
        Self {
            c,
            fock: std::array::from_fn(|s| {
                c.matmul_accurate(&fock[s].matmul_accurate(c, false), true)
            }),
            counts,
            pairs,
        }
    }

    fn difference(&self, s: usize, p: usize, q: usize) -> f64 {
        usize::from(p < self.counts[s]) as f64 - usize::from(q < self.counts[s]) as f64
    }

    pub(crate) fn gradient(&self) -> Vec<f64> {
        self.pairs
            .iter()
            .map(|&(p, q)| {
                2.0 * (0..2)
                    .map(|s| self.difference(s, p, q) * self.fock[s][(p, q)])
                    .sum::<f64>()
            })
            .collect()
    }

    pub(crate) fn diagonal(&self) -> Vec<f64> {
        self.pairs
            .iter()
            .map(|&(p, q)| {
                // This floor belongs only to the iterative preconditioner.
                (2.0 * (0..2)
                    .map(|s| {
                        self.difference(s, p, q) * (self.fock[s][(q, q)] - self.fock[s][(p, p)])
                    })
                    .sum::<f64>())
                .abs()
                .max(1e-4)
            })
            .collect()
    }

    fn generator(&self, x: &[f64]) -> Matrix {
        assert_eq!(x.len(), self.pairs.len());
        let mut k = Matrix::zeros(self.c.cols, self.c.cols);
        for (&(p, q), &value) in self.pairs.iter().zip(x) {
            k[(q, p)] = value;
            k[(p, q)] = -value;
        }
        k
    }

    pub(crate) fn rotate(&self, x: &[f64]) -> Matrix {
        self.c
            .matmul_seq(&orthogonal_exponential(&self.generator(x)))
    }

    /// Stable finite changes of both occupied projectors under one rotation.
    pub(crate) fn finite_density_change(&self, x: &[f64]) -> [Matrix; 2] {
        let generator = self.generator(x);
        std::array::from_fn(|s| {
            let delta = generator_density_change(&generator, self.counts[s]);
            self.c
                .matmul_accurate(&delta, false)
                .matmul_transpose_seq(self.c)
        })
    }

    /// Exact quadratic energy work without subtraction of absolute energies.
    pub(crate) fn quadratic_energy_work(
        &self,
        x: &[f64],
        delta: &[Matrix; 2],
        induced: &[Matrix; 2],
    ) -> f64 {
        let generator = self.generator(x);
        let mut sum = crate::linalg::AccurateSum::default();
        for s in 0..2 {
            let change = generator_density_change(&generator, self.counts[s]);
            for (&p, &f) in change.as_slice().iter().zip(self.fock[s].as_slice()) {
                sum.add_product(p, f);
            }
            for (&p, &f) in delta[s].as_slice().iter().zip(induced[s].as_slice()) {
                sum.add_product(0.5 * p, f);
            }
        }
        sum.value()
    }

    pub(crate) fn image(
        &self,
        x: &[f64],
        mut kernel: impl FnMut(&[Matrix; 2]) -> Result<[Matrix; 2]>,
    ) -> Result<Vec<f64>> {
        let k = self.generator(x);
        // d_s = [K,n_s]; the AO kernel sees both spin densities together.
        let density: [Matrix; 2] = std::array::from_fn(|s| {
            let mut d = k.clone();
            for i in 0..d.rows {
                for j in 0..d.cols {
                    d[(i, j)] *= -self.difference(s, i, j);
                }
            }
            d
        });
        let ao =
            std::array::from_fn(|s| self.c.matmul_seq(&density[s]).matmul_transpose_seq(self.c));
        let induced = kernel(&ao)?;
        let mut result = vec![0.0; x.len()];
        for s in 0..2 {
            let f = &self.fock[s];
            let fk = f.matmul_accurate(&k, false);
            let kf = k.matmul_accurate(f, false);
            let df = density[s].matmul_accurate(f, false);
            let fd = f.matmul_accurate(&density[s], false);
            let response = self
                .c
                .matmul_accurate(&induced[s].matmul_accurate(self.c, false), true);
            for (value, &(p, q)) in result.iter_mut().zip(&self.pairs) {
                let occupation = self.difference(s, p, q);
                // Symmetric exponential-coordinate curvature:
                // 1/2 [n,[F,K]] + 1/2 [[K,n],F] + [n,G([K,n])].
                *value += occupation * (fk[(p, q)] - kf[(p, q)]) + df[(p, q)] - fd[(p, q)]
                    + 2.0 * occupation * response[(p, q)];
            }
        }
        Ok(result)
    }
}

