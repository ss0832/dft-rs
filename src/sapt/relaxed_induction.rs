//! Orbital-relaxed third-order HF induction via the variational
//! orbital rotation of the separable, mutually polarized monomers.
//! This is the 2n+1 rule form of Patkowski et al. (2010), Eq. 28.

use crate::basis::MolBasis;
use crate::linalg::Matrix;
use crate::scf::{JkEngine, ScfResult};
use crate::Result;

pub(super) struct Monomer<'a> {
    pub(super) basis: &'a MolBasis,
    pub(super) scf: &'a ScfResult,
    pub(super) jk: &'a JkEngine,
    pub(super) overlap: &'a Matrix,
    pub(super) density_first: &'a [Matrix; 2],
    pub(super) perturbation: &'a Matrix,
}

pub(super) struct Contributions {
    pub(super) polarization: f64,
    pub(super) intramonomer: f64,
}

/// Occupied-to-virtual orbital rotation recovered from the first-order
/// spin density in the AO metric.
pub(super) fn orbital_response(m: &Monomer<'_>, spin: usize) -> Matrix {
    let channel = if m.scf.unrestricted { spin } else { 0 };
    let c = &m.scf.mo_coeff[channel];
    let no = [m.scf.n_alpha, m.scf.n_beta][spin];
    let nv = c.cols - no;
    let sc = m.overlap.matmul(c);
    let d = sc.transpose_matmul(&m.density_first[spin].matmul(&sc));
    let mut u = Matrix::zeros(nv, no);
    for a in 0..nv {
        for i in 0..no {
            u[(a, i)] = d[(no + a, i)];
        }
    }
    u
}

/// The second-order diagonal density blocks generated by the first-order
/// occupied-virtual rotation. An unknown second-order orbital amplitude
/// is unnecessary because its energy contributions cancel by stationarity.
fn density_second(m: &Monomer<'_>, spin: usize) -> Matrix {
    let channel = if m.scf.unrestricted { spin } else { 0 };
    let c = &m.scf.mo_coeff[channel];
    let u = orbital_response(m, spin);
    let (nv, no) = (u.rows, u.cols);
    let oo = u.transpose_matmul(&u);
    let vv = u.matmul_transpose_seq(&u);
    let mut diagonal = Matrix::zeros(c.cols, c.cols);
    for i in 0..no {
        for j in 0..no {
            diagonal[(i, j)] = -oo[(i, j)];
        }
    }
    for a in 0..nv {
        for b in 0..nv {
            diagonal[(no + a, no + b)] = vv[(a, b)];
        }
    }
    c.matmul(&diagonal).matmul_transpose_seq(c)
}

pub(super) fn density_fock(m: &Monomer<'_>) -> Result<[Matrix; 2]> {
    let total_first = Matrix::from_row_major(
        m.basis.nao_sph,
        m.basis.nao_sph,
        m.density_first[0]
            .as_slice()
            .iter()
            .zip(m.density_first[1].as_slice())
            .map(|(a, b)| a + b)
            .collect(),
    );
    let (j, k) = m.jk.build(
        m.basis,
        &total_first,
        [&m.density_first[0], &m.density_first[1]],
        true,
    )?;
    Ok(k.map(|exchange| {
        Matrix::from_row_major(
            j.rows,
            j.cols,
            j.as_slice()
                .iter()
                .zip(exchange.as_slice())
                .map(|(j, k)| j - k)
                .collect(),
        )
    }))
}

pub(super) fn monomer(m: &Monomer<'_>) -> Result<Contributions> {
    let second = [0, 1].map(|spin| density_second(m, spin));
    let density_fock = density_fock(m)?;
    let mut polarization = 0.0;
    let mut intramonomer = 0.0;
    for (d, df) in second.iter().zip(density_fock) {
        polarization += d.frobenius_dot(m.perturbation);
        // The cubic coefficient of the monomer HF energy equals
        // Tr(F'[D1] D2). The cubic density has only occupied-virtual
        // blocks and its contraction with the stationary Fock is zero.
        intramonomer += d.frobenius_dot(&df);
    }
    Ok(Contributions {
        polarization,
        intramonomer,
    })
}
