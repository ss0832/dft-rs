# Aqueous G_CDS for molecules that EXERCISE the measured pairwise terms.
#
# The pair coefficients were fitted on diatomic scans, where the two atoms'
# areas move together. Real molecules have several partners at once and very
# different area ratios, so this is the test that says whether the fitted
# split between the two atoms is right — not just whether the diatomic curve
# is reproduced.
from pyscf import gto
from pyscf.solvent import smd

CASES = [
    ("CH4", "C 0 0 0; H 0.629 0.629 0.629; H -0.629 -0.629 0.629; "
            "H 0.629 -0.629 -0.629; H -0.629 0.629 -0.629"),
    ("C2H6", "C 0 0 0.7680; C 0 0 -0.7680; "
             "H 1.0192 0 1.1573; H -0.5096 0.8827 1.1573; "
             "H -0.5096 -0.8827 1.1573; H -1.0192 0 -1.1573; "
             "H 0.5096 -0.8827 -1.1573; H 0.5096 0.8827 -1.1573"),
    ("C2H4", "C 0 0 0.6695; C 0 0 -0.6695; "
             "H 0 0.9289 1.2321; H 0 -0.9289 1.2321; "
             "H 0 0.9289 -1.2321; H 0 -0.9289 -1.2321"),
    ("C2H2", "C 0 0 0.6015; C 0 0 -0.6015; H 0 0 1.6635; H 0 0 -1.6635"),
    ("C3H8", "C 0 0 0.5875; C 0 1.2681 -0.2600; C 0 -1.2681 -0.2600; "
             "H 0.8760 0 1.2400; H -0.8760 0 1.2400; "
             "H 0 2.1499 0.3893; H 0 -2.1499 0.3893; "
             "H 0.8800 1.3106 -0.9100; H -0.8800 1.3106 -0.9100; "
             "H 0.8800 -1.3106 -0.9100; H -0.8800 -1.3106 -0.9100"),
    ("benzene", None),  # generated below
    ("cyclopropane", "C 0 0.8703 0; C 0.7537 -0.4351 0; C -0.7537 -0.4351 0; "
                     "H 0 1.4595 0.9126; H 0 1.4595 -0.9126; "
                     "H 1.2640 -0.7298 0.9126; H 1.2640 -0.7298 -0.9126; "
                     "H -1.2640 -0.7298 0.9126; H -1.2640 -0.7298 -0.9126"),
    ("PH3O", "P 0 0 0; O 0 0 1.476; H 1.199 0 -0.513; "
             "H -0.600 1.039 -0.513; H -0.600 -1.039 -0.513"),
]

import math

bz = []
for k in range(6):
    a = k * math.pi / 3.0
    bz.append(f"C {1.39 * math.cos(a):.6f} {1.39 * math.sin(a):.6f} 0.0")
for k in range(6):
    a = k * math.pi / 3.0
    bz.append(f"H {2.48 * math.cos(a):.6f} {2.48 * math.sin(a):.6f} 0.0")
BENZENE = "; ".join(bz)

print("# PROVENANCE: generated by tools/oracle/gen_smd_water_pairs.py against")
print("# PySCF's SMD module, used as a NUMERICAL ORACLE only. Units: Hartree.")
print("# label,g_cds_hartree")
for label, spec in CASES:
    if spec is None:
        spec = BENZENE
    mol = gto.M(atom=spec, basis="sto-3g", spin=None, verbose=0)
    obj = smd.SMD(mol)
    obj.solvent = "water"
    g, _ = smd.get_cds_legacy(obj)
    print(f"{label},{g:.12e}")
