import math

bz = []
for k in range(6):
    a = k * math.pi / 3.0
    bz.append((6, (1.39 * math.cos(a), 1.39 * math.sin(a), 0.0)))
for k in range(6):
    a = k * math.pi / 3.0
    bz.append((1, (2.48 * math.cos(a), 2.48 * math.sin(a), 0.0)))
MOLECULES["benzene"] = bz

# (name, s6, s8, a1, a2) -- B3LYP-D4 and PBE0-D4 style damping, given
# explicitly so the gate does not depend on dftd4's internal parameter file.
PARAMS = {
    "b3lyp": dict(s6=1.0, s8=2.02929367, a1=0.40868035, a2=4.53807137),
    "pbe0": dict(s6=1.0, s8=1.20065498, a1=0.40085597, a2=5.02928789),
}

MODELS = ["d4", "d4s"]


def build(atoms, model, charge=0.0):
    numbers = np.array([z for z, _ in atoms])
    pos = np.array([[c * BOHR for c in xyz] for _, xyz in atoms])
    kw = {}
    if model != "d4":
        kw["model"] = model
    try:
        return DispersionModel(numbers, pos, charge, **kw)
    except TypeError:
        return None


def main():
    print("# PROVENANCE: generated by tools/oracle/gen_d4.py against the dftd4")
    print("# package, used as a NUMERICAL ORACLE only (LGPL-3.0: no code or")
    print("# parameter data is taken from it). Units: Hartree.")
    print("# model,functional,molecule,e_disp")
    for model in MODELS:
        for fname, p in PARAMS.items():
            par = DampingParam(**p)
            for name, atoms in MOLECULES.items():
                m = build(atoms, model)
                if m is None:
                    print(f"# model {model}: not accepted by this build",
                          file=sys.stderr)
                    break
                try:
                    res = m.get_dispersion(par, grad=False)
                except Exception as exc:
                    print(f"# {model}/{fname}/{name}: {exc}", file=sys.stderr)
                    continue
                print(f"{model},{fname},{name},{res['energy']:.14e}")


if __name__ == "__main__":
    main()
