# Freeze a non-aqueous SMD G_CDS oracle. Every molecule here is built only
# from pair-term-free elements for the non-aqueous column (measured by
# measure_smd_nonaq_pairs.py), so the atomic sum is the exact answer and
# any disagreement is a bug in dft-rs rather than a missing parameter.
from pyscf import gto
from pyscf.solvent import smd

K = 627.5094740631

CASES = [
    ("HF", "H 0 0 0; F 0 0 0.917", "benzene"),
    ("HF", "H 0 0 0; F 0 0 0.917", "acetonitrile"),
    ("H2S", "S 0 0 0; H 0 0 1.336; H 1.294 0 -0.335", "cyclohexane"),
    ("PH3", "P 0 0 0; H 1.192 0 0.772; H -0.596 1.032 0.772; "
            "H -0.596 -1.032 0.772", "chloroform"),
    ("SiH4", "Si 0 0 0; H 0.856 0.856 0.856; H -0.856 -0.856 0.856; "
             "H 0.856 -0.856 -0.856; H -0.856 0.856 -0.856", "toluene"),
    ("HCl", "H 0 0 0; Cl 0 0 1.275", "1,4-dioxane"),
    ("Br2", "Br 0 0 0; Br 0 0 2.281", "carbon tetrachloride"),
    ("NH3", "N 0 0 0; H 0.937 0 0.381; H -0.469 0.812 0.381; "
            "H -0.469 -0.812 0.381", "methanol"),
]

print("# PROVENANCE: generated by tools/oracle/gen_smd_nonaq.py against")
print("# PySCF's SMD module, used as a NUMERICAL ORACLE only (no code or")
print("# data is taken from it). Regenerate to update; a diff here is a")
print("# code change and needs review. Units: Hartree.")
print("# label,solvent,g_cds_hartree")
for label, spec, solvent in CASES:
    mol = gto.M(atom=spec, basis="sto-3g", spin=None, verbose=0)
    obj = smd.SMD(mol)
    obj.solvent = solvent
    g, _ = smd.get_cds_legacy(obj)
    print(f"{label},{solvent},{g:.12e}")
