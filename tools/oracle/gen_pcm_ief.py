# Freeze an IEF-PCM / SS(V)PE oracle alongside the existing C-PCM one, so
# the D-matrix path has a numerical reference of its own.
#
# The comparison is made on the SOLVATION SHIFT: our cavity uses a
# self-generated quasi-uniform tessellation while the reference uses a
# Lebedev rule, so the two discretize the same continuum model slightly
# differently and only the shift is meaningful at tight tolerance.
from pyscf import gto, scf
from pyscf import solvent

MOL = """
O  0.00000000  0.02645000  0.11730000
H  0.01587000  0.75714000 -0.46915000
H  0.00000000 -0.75714000 -0.46915000
"""


def run(method, eps):
    mol = gto.M(atom=MOL, basis="sto-3g", verbose=0)
    gas = scf.RHF(mol).run().e_tot
    mf = solvent.PCM(scf.RHF(mol))
    mf.with_solvent.method = method
    mf.with_solvent.eps = eps
    mf.with_solvent.lebedev_order = 29
    mf.with_solvent.vdw_scale = 1.2
    sol = mf.run().e_tot
    return gas, sol


print("# PROVENANCE: generated by tools/oracle/gen_pcm_ief.py against PySCF's")
print("# PCM module, used as a NUMERICAL ORACLE only. Units: Hartree.")
print("# key,value")
eps = 78.3553
for method in ("IEF-PCM", "SS(V)PE", "COSMO", "C-PCM"):
    gas, sol = run(method, eps)
    print(f"e_gas,{gas:.12f}")
    print(f"dg_{method},{sol - gas:.12f}")
